-- Module registry behaviour through real cross-resource registration
-- (SDK -> exports -> registry), using in-memory fixture resources.

local function simple(name, version, deps, extra)
    return string.format([[
local M = Wasteland.DefineModule({
    name = %q, version = %q, dependencies = %s, %s
    onInit = function(M, ctx) track('init:' .. M.name) end,
    onShutdown = function(M, reason) track('shutdown:' .. reason) end,
})
]], name, version, deps or '{}', extra or '')
end

describe('dependency ordering', function()
    local server = newServer()
    -- Registered in reverse order on purpose: gamma before beta before alpha.
    addModule(server, 'fx_gamma', simple('gamma', '1.0.0', "{ beta = '^1.0.0' }", "optionalDependencies = { delta = '^1.0.0' },"))
    addModule(server, 'fx_beta', simple('beta', '1.1.0', "{ alpha = '^1.0.0' }"))
    addModule(server, 'fx_alpha', simple('alpha', '1.2.0', "{ core = '^1.0.0' }"))
    server:start('wasteland_core')
    server:start('fx_gamma')
    server:start('fx_beta')

    it('waits for unregistered dependencies with a clear reason', function()
        local s = server:export('wasteland_core', 'GetModuleStatus', 'beta')
        expect(s.state).toBe('waiting')
        expect(s.reason).toBe('waiting for dependency "alpha" to register')
        expect(server:export('wasteland_core', 'GetModuleStatus', 'gamma').reason).toBe('waiting for dependency "beta" (waiting)')
    end)

    it('initialises in dependency order once the dependency arrives', function()
        server:start('fx_alpha')
        local st = states(server)
        expect(st.alpha).toBe('running'); expect(st.beta).toBe('running'); expect(st.gamma).toBe('running')
        local a = server:export('wasteland_core', 'GetModuleStatus', 'alpha')
        local b = server:export('wasteland_core', 'GetModuleStatus', 'beta')
        local g = server:export('wasteland_core', 'GetModuleStatus', 'gamma')
        expect(a.initIndex < b.initIndex).toBe(true)
        expect(b.initIndex < g.initIndex).toBe(true)
    end)

    it('optional dependencies that never register do not block', function()
        expect(states(server).gamma).toBe('running')
        expect(states(server).delta).toBe(nil)
    end)

    it('stopping a dependency shuts down dependents and puts them back to waiting', function()
        server:stop('fx_alpha')
        local st = states(server)
        expect(st.alpha).toBe('stopped'); expect(st.beta).toBe('waiting'); expect(st.gamma).toBe('waiting')
        local gCalls = server:export('fx_gamma', 'Calls')
        local bCalls = server:export('fx_beta', 'Calls')
        expect(gCalls[#gCalls]).toBe('shutdown:dependency_unavailable:beta')
        expect(bCalls[#bCalls]).toBe('shutdown:dependency_unavailable:alpha')
    end)

    it('restarting the dependency re-initialises dependents (with config re-read)', function()
        server:start('fx_alpha')
        local st = states(server)
        expect(st.alpha).toBe('running'); expect(st.beta).toBe('running'); expect(st.gamma).toBe('running')
        local bCalls = server:export('fx_beta', 'Calls')
        expect(bCalls).toEqual({ 'init:beta', 'shutdown:dependency_unavailable:alpha', 'init:beta' })
        expect(#server.scriptErrors).toBe(0)
    end)
end)

describe('rejections and failures', function()
    local server = newServer()
    addModule(server, 'fx_alpha', simple('alpha', '1.2.0'))
    addModule(server, 'fx_dup', simple('alpha', '9.0.0'))
    addModule(server, 'fx_badver', simple('badver', '1.0'))
    addModule(server, 'fx_wants2', simple('wants2', '1.0.0', "{ alpha = '^2.0.0' }"))
    addModule(server, 'fx_newcore', simple('newcore', '1.0.0', '{}', "core = '^2.0.0',"))
    addModule(server, 'fx_crash', [[
Wasteland.DefineModule({ name = 'crash', version = '1.0.0',
    onInit = function(M) track('init'); error('boom') end,
    onShutdown = function(M, reason) track('cleanup:' .. reason) end })
]])
    addModule(server, 'fx_false', [[
Wasteland.DefineModule({ name = 'falsy', version = '1.0.0',
    onInit = function() return false, 'missing data' end })
]])
    addModule(server, 'fx_cyc_a', simple('cyca', '1.0.0', "{ cycb = '*' }"))
    addModule(server, 'fx_cyc_b', simple('cycb', '1.0.0', "{ cyca = '*' }"))
    addModule(server, 'fx_badschema', simple('badschema', '1.0.0', '{}',
        "config = { file = 'badschema.lua', schema = { type = 'table', fields = { x = { type = 'strnig' } } } },"))
    for _, r in ipairs({ 'fx_alpha', 'fx_dup', 'fx_badver', 'fx_wants2', 'fx_newcore', 'fx_crash', 'fx_false',
        'fx_cyc_a', 'fx_cyc_b', 'fx_badschema' }) do
        server:start(r)
    end
    local st = states(server)

    it('rejects a duplicate module name from another resource', function()
        expect(server:export('wasteland_core', 'GetModuleStatus', 'alpha').resource).toBe('fx_alpha')
        expect(#server:lines('module name "alpha" is already registered by resource "fx_alpha" (attempted by "fx_dup")') > 0).toBe(true)
    end)
    it('rejects invalid versions and invalid config schemas at registration', function()
        expect(st.badver).toBe(nil)
        expect(#server:lines('invalid version "1.0"') > 0).toBe(true)
        expect(st.badschema).toBe(nil)
        expect(#server:lines('unknown schema type "strnig"') > 0).toBe(true)
    end)
    it('fails a module whose dependency version is incompatible', function()
        expect(st.wants2).toBe('failed')
        expect(server:export('wasteland_core', 'GetModuleStatus', 'wants2').reason)
            .toBe('dependency "alpha" api 1.2.0 does not satisfy required range ^2.0.0')
    end)
    it('fails a module that requires a newer core api', function()
        expect(st.newcore).toBe('failed')
        expect(server:export('wasteland_core', 'GetModuleStatus', 'newcore').reason).toContain('requires core api ^2.0.0')
    end)
    it('fails a module whose init throws, after running its cleanup', function()
        expect(st.crash).toBe('failed')
        expect(server:export('wasteland_core', 'GetModuleStatus', 'crash').reason).toContain('boom')
        expect(server:export('fx_crash', 'Calls')).toEqual({ 'init', 'cleanup:init_failed' })
    end)
    it('fails a module whose init returns false, with its reason', function()
        expect(st.falsy).toBe('failed')
        expect(server:export('wasteland_core', 'GetModuleStatus', 'falsy').reason).toBe('init returned false: missing data')
    end)
    it('detects dependency cycles', function()
        expect(st.cyca).toBe('failed'); expect(st.cycb).toBe('failed')
        expect(server:export('wasteland_core', 'GetModuleStatus', 'cyca').reason).toContain('dependency cycle')
    end)
    it('keeps other modules running despite failures', function()
        expect(st.alpha).toBe('running')
    end)
    it('the SDK reports registration failures in the module resource', function()
        expect(#server:lines('[badver] registration failed') > 0).toBe(true)
    end)
end)

describe('module configuration', function()
    local mod = [[
Wasteland.DefineModule({ name = 'cfgmod', version = '1.0.0',
    config = { file = 'cfgmod.lua', optional = false, schema = { type = 'table', fields = {
        speed = { type = 'number', min = 0, max = 10, default = 1 },
        label = { type = 'string', required = true },
    } } },
    onInit = function(M) track(M.config.speed); track(M.config.label) end })
]]
    it('passes validated config (with defaults) to onInit', function()
        local server = newServer({ config = { ['cfgmod.lua'] = "return { label = 'hi' }" } })
        addModule(server, 'fx_cfg', mod)
        server:start('fx_cfg')
        expect(states(server).cfgmod).toBe('running')
        expect(server:export('fx_cfg', 'Calls')).toEqual({ 1, 'hi' })
    end)
    it('fails the module with file/setting/expected-value errors for bad config', function()
        local server = newServer({ config = { ['cfgmod.lua'] = "return { speed = 50, colour = 'red' }" } })
        addModule(server, 'fx_cfg', mod)
        server:start('fx_cfg')
        local s = server:export('wasteland_core', 'GetModuleStatus', 'cfgmod')
        expect(s.state).toBe('failed')
        expect(s.reason).toContain("wasteland_config/config/cfgmod.lua: setting 'label': missing required setting")
        expect(s.reason).toContain("setting 'speed': expected a number between 0 and 10, got 50")
        expect(#server:lines("setting 'colour': unknown setting (ignored); check for a typo") > 0).toBe(true)
        expect(#server:export('fx_cfg', 'Calls')).toBe(0)
    end)
    it('fails when a required config file is missing', function()
        local server = newServer()
        addModule(server, 'fx_cfg', mod)
        server:start('fx_cfg')
        expect(server:export('wasteland_core', 'GetModuleStatus', 'cfgmod').reason).toContain('cfgmod.lua: file not found')
    end)
end)

describe('module activation (modules.lua)', function()
    it('disabled modules register but never initialise; dependents fail clearly', function()
        local server = newServer({ config = { ['modules.lua'] = 'return { enabled = { alpha = false } }' } })
        addModule(server, 'fx_alpha', simple('alpha', '1.0.0'))
        addModule(server, 'fx_beta', simple('beta', '1.0.0', "{ alpha = '^1.0.0' }"))
        server:start('fx_alpha'); server:start('fx_beta')
        local st = states(server)
        expect(st.alpha).toBe('disabled')
        expect(st.beta).toBe('failed')
        expect(server:export('wasteland_core', 'GetModuleStatus', 'beta').reason).toBe('required dependency "alpha" is disabled')
        expect(#server:export('fx_alpha', 'Calls')).toBe(0)
    end)
    it('unlisted = disable turns off modules not listed', function()
        local server = newServer({ config = { ['modules.lua'] = "return { enabled = { alpha = true }, unlisted = 'disable' }" } })
        addModule(server, 'fx_alpha', simple('alpha', '1.0.0'))
        addModule(server, 'fx_other', simple('other', '1.0.0'))
        server:start('fx_alpha'); server:start('fx_other'); server:start('wasteland_template')
        local st = states(server)
        expect(st.alpha).toBe('running'); expect(st.other).toBe('disabled'); expect(st.template).toBe('disabled')
    end)
    it('a disabled dependency that has not registered fails dependents immediately', function()
        local server = newServer({ config = { ['modules.lua'] = 'return { enabled = { alpha = false } }' } })
        addModule(server, 'fx_beta', simple('beta', '1.0.0', "{ alpha = '*' }"))
        server:start('fx_beta')
        expect(server:export('wasteland_core', 'GetModuleStatus', 'beta').reason)
            .toBe('required dependency "alpha" is disabled in modules config')
    end)
end)

describe('async modules', function()
    local server = newServer({ config = { ['framework.lua'] = 'return { startupTimeoutSeconds = 10 }' } })
    addModule(server, 'fx_async', [[
local M
M = Wasteland.DefineModule({ name = 'slow', version = '1.0.0', async = true,
    onInit = function(M) Citizen.CreateThread(function() Citizen.Wait(2000); track('ready'); M.ready() end) end })
]])
    addModule(server, 'fx_dependent', simple('needsslow', '1.0.0', "{ slow = '^1.0.0' }"))
    addModule(server, 'fx_never', [[
Wasteland.DefineModule({ name = 'never', version = '1.0.0', async = true,
    onInit = function() end, onShutdown = function(M, r) track('shutdown:' .. r) end })
]])
    server:start('fx_async'); server:start('fx_dependent'); server:start('fx_never')

    it('stay initializing until they report ready; dependents wait', function()
        expect(states(server).slow).toBe('initializing')
        expect(states(server).needsslow).toBe('waiting')
    end)
    it('become running after M.ready(), releasing dependents', function()
        server:advance(2500)
        expect(states(server).slow).toBe('running')
        expect(states(server).needsslow).toBe('running')
    end)
    it('are failed when they never report ready within the startup timeout', function()
        server:advance(10000)
        local s = server:export('wasteland_core', 'GetModuleStatus', 'never')
        expect(s.state).toBe('failed')
        expect(s.reason).toBe('did not report ready within the startup timeout')
    end)
    it('cannot be reported ready by a resource that does not own them', function()
        addModule(server, 'fx_intruder', "RESULT = { exports.wasteland_core:ReportModuleReady('never') }")
        server:start('fx_intruder')
        expect(#server.scriptErrors).toBe(0)
        expect(states(server).never).toBe('failed')
    end)
end)

describe('core restart', function()
    local server = newServer()
    addModule(server, 'fx_alpha', simple('alpha', '1.0.0'))
    server:start('fx_alpha')
    it('modules come back after the core and its dependents are restarted', function()
        server:stop('wasteland_core')
        expect(server.resources.fx_alpha.state).toBe('stopped')
        server:start('fx_alpha')
        expect(states(server).alpha).toBe('running')
        expect(server:export('fx_alpha', 'Calls')).toEqual({ 'init:alpha' })
        expect(#server.scriptErrors).toBe(0)
    end)
end)

describe('core restart while module resources keep running', function()
    local server = newServer({ cascadeStop = false })
    addModule(server, 'fx_alpha', [[
Wasteland.DefineModule({ name = 'alpha', version = '1.0.0',
    onInit = function() track('init') end,
    onShutdown = function(M, reason) track('shutdown:' .. reason) end })
]])
    server:start('fx_alpha')
    it('the module shuts down locally, then re-registers and re-initialises when the core returns', function()
        server:stop('wasteland_core')
        expect(server.resources.fx_alpha.state).toBe('started')
        server:start('wasteland_core')
        expect(states(server).alpha).toBe('running')
        expect(server:export('fx_alpha', 'Calls')).toEqual({ 'init', 'shutdown:core_stopped', 'init' })
        expect(#server.scriptErrors).toBe(0)
    end)
end)
