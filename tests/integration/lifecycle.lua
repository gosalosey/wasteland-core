-- Startup reporting and ordered shutdown.

local function mod(name, deps)
    return string.format([[
Wasteland.DefineModule({ name = %q, version = '1.0.0', dependencies = %s,
    onShutdown = function(M, reason) exports.wasteland_core:Log('order', 'info', 'stop ' .. M.name .. ' ' .. reason) end })
]], name, deps)
end

describe('startup report', function()
    local server = newServer({ config = {
        ['modules.lua'] = "return { enabled = { template = true, inventory = true } }",
        ['framework.lua'] = 'return { startupTimeoutSeconds = 5 }',
    } })
    addModule(server, 'fx_orphan', mod('orphan', "{ zombies = '^1.0.0' }"))
    server:start('wasteland_template'); server:start('fx_orphan')
    server:advance(5000)

    it('warns about enabled modules that never registered', function()
        expect(#server:lines('module "inventory" is enabled in modules config but never registered') > 0).toBe(true)
    end)
    it('warns about modules still waiting, with the reason', function()
        expect(#server:lines('module "orphan" is still waiting: waiting for dependency "zombies" to register') > 0).toBe(true)
    end)
    it('emits wasteland:core:ready and the status table', function()
        expect(server:export('wasteland_core', 'IsReady')).toBe(true)
        expect(#server:lines('summary: running=2 waiting=1 missing=1') > 0).toBe(true)
    end)
end)

describe('ordered shutdown', function()
    local server = newServer()
    addModule(server, 'fx_a', mod('a', '{}'))
    addModule(server, 'fx_b', mod('b', "{ a = '*' }"))
    addModule(server, 'fx_c', mod('c', "{ b = '*' }"))
    server:start('fx_a'); server:start('fx_b'); server:start('fx_c')

    it('txAdmin shutdown stops modules in reverse initialisation order exactly once', function()
        server:clearOutput()
        server:txAdminShutdown()
        local stops = server:lines('stop ')
        expect(#stops).toBe(3)
        expect(stops[1]).toContain('stop c server_shutdown')
        expect(stops[2]).toContain('stop b server_shutdown')
        expect(stops[3]).toContain('stop a server_shutdown')
        expect(server:export('wasteland_core', 'GetFrameworkInfo').state).toBe('stopped')
        expect(#server:lines('stopped 3 module(s) in order: c, b, a')).toBe(1)
        expect(#server:lines('shutdown complete')).toBe(1)
    end)
    it('a second shutdown signal (resource stop) is a no-op', function()
        server:clearOutput()
        server:stop('wasteland_core')
        expect(#server:lines('stop ')).toBe(0)
        expect(#server.scriptErrors).toBe(0)
    end)
end)

describe('shutdown with a failing module', function()
    local server = newServer()
    addModule(server, 'fx_bad', [[
Wasteland.DefineModule({ name = 'badstop', version = '1.0.0', onShutdown = function() error('disk on fire') end })
]])
    addModule(server, 'fx_good', mod('good', '{}'))
    server:start('fx_bad'); server:start('fx_good')
    it('reports the error and still stops the remaining modules', function()
        server:clearOutput()
        server:txAdminShutdown()
        expect(#server:lines('disk on fire') > 0).toBe(true)
        expect(#server:lines('stop good server_shutdown')).toBe(1)
        expect(#server:lines('shutdown finished with 1 module error(s)')).toBe(1)
    end)
end)

describe('module events', function()
    local server = newServer()
    addModule(server, 'fx_listener', [[
AddEventHandler('wasteland:core:moduleState', function(name, state, prev) track(name .. ':' .. state) end)
AddEventHandler('wasteland:core:ready', function(info) track('ready:' .. info.name) end)
]])
    server:start('fx_listener')
    server:start('wasteland_template')
    server:advance(30000)
    it('broadcasts module state changes and readiness to other resources', function()
        local calls = server:export('fx_listener', 'Calls')
        expect(calls).toContain('template:waiting')
        expect(calls).toContain('template:running')
        expect(calls[#calls]).toBe('ready:Wasteland Core')
    end)
end)

describe('restart wasteland_core (runtime finding R1.7)', function()
    it('restarts module resources that FiveM stopped because the core stopped', function()
        local server = newServer()
        server:start('wasteland_template')
        server:advance(5000)
        server:restart('wasteland_core')
        -- FiveM behaviour (confirmed on a real server): dependents are stopped, not restarted.
        expect(server.resources.wasteland_template.state).toBe('stopped')
        expect(#server:lines('will restart 1 module resource(s) when the core starts again: wasteland_template')).toBe(1)
        server:advance(0)
        expect(server.resources.wasteland_template.state).toBe('started')
        expect(states(server).template).toBe('running')
        expect(#server:lines('restarting module resource "wasteland_template" (stopped by the previous core restart)')).toBe(1)
        expect(#server.scriptErrors).toBe(0)
    end)

    it('does not restart a module resource an admin stopped on purpose earlier', function()
        local server = newServer()
        server:start('wasteland_template')
        server:advance(5000)
        server:stop('wasteland_template')
        server:advance(60000)
        server:restart('wasteland_core')
        server:advance(0)
        expect(server.resources.wasteland_template.state).toBe('stopped')
        expect(#server:lines('restarting module resource')).toBe(0)
    end)

    it('the restart list is consumed once (a later plain core start does not restart again)', function()
        local server = newServer()
        server:start('wasteland_template')
        server:restart('wasteland_core')
        server:advance(0)
        expect(server.convars.wasteland_core_restart_resources).toBe('')
    end)

    it('can be turned off with framework.restartModulesAfterCoreRestart = false', function()
        local server = newServer({ config = { ['framework.lua'] = 'return { restartModulesAfterCoreRestart = false }' } })
        server:start('wasteland_template')
        server:restart('wasteland_core')
        server:advance(0)
        expect(server.resources.wasteland_template.state).toBe('stopped')
        expect(states(server).template).toBe(nil)
    end)
end)
