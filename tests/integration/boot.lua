-- Milestone 1 acceptance: framework starts without other gameplay
-- frameworks, loads configuration, reports module status, shuts down cleanly.

describe('boot (shipped resources, default config)', function()
    local server = newServer()
    local ok, err = server:start('wasteland_template')

    it('starts the template, core and config resources (dependencies auto-start)', function()
        expect(ok).toBe(true)
        expect(err).toBe(nil)
        expect(server.resources.wasteland_core.state).toBe('started')
        expect(server.resources.wasteland_config.state).toBe('started')
    end)

    it('raises no script errors', function()
        expect(#server.scriptErrors).toBe(0)
    end)

    it('loads configuration and reports framework info', function()
        local info = server:export('wasteland_core', 'GetFrameworkInfo')
        expect(info.name).toBe('Wasteland Core')
        expect(info.version).toBe("0.2.0")
        expect(info.api).toBe('1.1.0')
        expect(info.state).toBe('booting')
    end)

    it('registers and initialises the template module with its validated config', function()
        local s = server:export('wasteland_core', 'GetModuleStatus', 'template')
        expect(s.state).toBe('running')
        expect(s.resource).toBe('wasteland_template')
        local cfg = server:export('wasteland_core', 'GetModuleConfig', 'template')
        expect(cfg.greeting).toBe('Template module is running')
        expect(cfg.heartbeatSeconds).toBe(60)
        expect(server:lines('Template module is running (framework Wasteland Core v0.2.0)')).toHaveLength(1)
    end)

    it('becomes ready after the startup window and prints a status report', function()
        server:advance(30 * 1000)
        expect(server:export('wasteland_core', 'IsReady')).toBe(true)
        local report = server:lines('summary:')
        expect(report).toHaveLength(1)
        expect(report[1]).toContain('running=2')
    end)

    it('runs module threads (template heartbeat) without errors', function()
        server:advance(5 * 60 * 1000)
        expect(#server.scriptErrors).toBe(0)
    end)

    it('shuts down cleanly when the core stops (dependents first)', function()
        server:clearOutput()
        server:stop('wasteland_core')
        expect(server.resources.wasteland_template.state).toBe('stopped')
        expect(server.resources.wasteland_core.state).toBe('stopped')
        expect(server:lines('template module stopped (resource_stop)')).toHaveLength(1)
        expect(server:lines('shutdown complete')).toHaveLength(1)
        expect(#server.scriptErrors).toBe(0)
    end)

    it('starts again after a full restart', function()
        server:clearOutput()
        expect((server:start('wasteland_template'))).toBe(true)
        expect(states(server).template).toBe('running')
        expect(#server.scriptErrors).toBe(0)
    end)
end)

describe('boot with invalid core configuration', function()
    local server = newServer({ config = {
        ['logging.lua'] = "return { level = 'verbose' }",
        ['framework.lua'] = "return { startupTimeoutSeconds = 0 }",
    } })
    server:start('wasteland_template')

    it('reports each problem with file, setting and expected value', function()
        expect(server:lines("wasteland_config/config/logging.lua: setting 'level': expected one of \"debug\", \"info\", \"warn\", \"error\", \"off\", got \"verbose\" (string)")).toHaveLength(1)
        expect(server:lines("wasteland_config/config/framework.lua: setting 'startupTimeoutSeconds': expected an integer between 1 and 600, got 0")).toHaveLength(1)
    end)

    it('does not initialise any module and reports config_error', function()
        expect(server:export('wasteland_core', 'GetFrameworkInfo').state).toBe('config_error')
        expect(states(server).template).toBe('waiting')
        expect(server:export('wasteland_core', 'GetModuleStatus', 'template').reason).toBe('framework configuration is invalid')
    end)

    it('resumes startup after the config is fixed and `config reload` is run', function()
        server:setFile('wasteland_config', 'config/logging.lua', "return { level = 'info' }")
        server:setFile('wasteland_config', 'config/framework.lua', 'return {}')
        server:command(0, 'wasteland config reload')
        expect(server:lines('OK: configuration valid; startup resumed')).toHaveLength(1)
        expect(states(server).template).toBe('running')
        expect(#server.scriptErrors).toBe(0)
    end)
end)

describe('boot with a missing config file', function()
    local server = newServer({ config = { ['modules.lua'] = false } })
    server:start('wasteland_core')
    it('reports the missing file instead of silently using defaults', function()
        expect(server:lines('wasteland_config/config/modules.lua: file not found')).toHaveLength(1)
        expect(server:export('wasteland_core', 'GetFrameworkInfo').state).toBe('config_error')
    end)
end)

describe('custom framework name and command', function()
    local server = newServer({ config = { ['framework.lua'] = "return { name = 'Dead Ground', shortName = 'dg' }" } })
    server:start('wasteland_template')
    it('uses the configured name in info, logs and the command name', function()
        expect(server:export('wasteland_core', 'GetFrameworkInfo').name).toBe('Dead Ground')
        expect(#server:lines('[Dead Ground]') > 0).toBe(true)
        expect(server:command(0, 'dg version')).toBe(true)
        expect(server:lines('Dead Ground v0.2.0 (api 1.1.0)')).toHaveLength(1)
        expect(server:command(0, 'wasteland version')).toBe(false)
    end)
end)
