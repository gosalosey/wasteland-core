-- Zombie rules (wasteland_zombies/shared/rules.lua) with the shipped config.

local env = setmetatable({}, { __index = _G })
assert(loadfile(RESOURCES .. '/wasteland_zombies/shared/rules.lua', 't', env))()
local Rules = env.WLZ.Rules

local function shippedConfig()
    local f = assert(io.open(RESOURCES .. '/wasteland_config/config/zombies.lua', 'rb'))
    local src = f:read('a'); f:close()
    return assert(load(src, '@zombies.lua', 't', { math = math }))()
end
local cfg = shippedConfig()
local pop = cfg.population

describe('zombie population', function()
    it('keeps 12 around a player by day and 18 at night', function()
        expect(Rules.target(pop, false)).toBe(12)
        expect(Rules.target(pop, true)).toBe(18)
        expect(Rules.isNight(22)).toBe(true); expect(Rules.isNight(5)).toBe(true); expect(Rules.isNight(12)).toBe(false)
    end)
    it('tops up in batches and never past the world cap', function()
        expect(Rules.toSpawn(pop, false, 0, 0)).toBe(3)
        expect(Rules.toSpawn(pop, false, 11, 0)).toBe(1)
        expect(Rules.toSpawn(pop, false, 12, 0)).toBe(0)
        expect(Rules.toSpawn(pop, false, 0, 89)).toBe(1)
        expect(Rules.toSpawn(pop, false, 0, 90)).toBe(0)
    end)
    it('mostly walkers; more runners at night', function()
        expect(Rules.pickKind(cfg.kinds, false, 0.10)).toBe('runner')
        expect(Rules.pickKind(cfg.kinds, false, 0.30)).toBe('walker')
        expect(Rules.pickKind(cfg.kinds, true, 0.40)).toBe('runner')
        expect(Rules.pickKind(cfg.kinds, true, 0.50)).toBe('walker')
    end)
    it('any number of kinds: each its chance, in name order, the rest walkers', function()
        local kinds = { walker = {}, runner = { chance = 20, nightChance = 20 }, brute = { chance = 5, nightChance = 10 } }
        expect(Rules.pickKind(kinds, false, 0.03)).toBe('brute')   -- brute 0-5 %
        expect(Rules.pickKind(kinds, false, 0.10)).toBe('runner')  -- runner 5-25 %
        expect(Rules.pickKind(kinds, false, 0.30)).toBe('walker')
        expect(Rules.pickKind(kinds, true, 0.08)).toBe('brute')
    end)
    it('models: the kind own list, else the general list; never one a game lacks', function()
        local general = { 'a', 'b' }
        expect(table.concat(Rules.modelPool({ models = { 'x', 'y' } }, general, {}), ',')).toBe('x,y')
        expect(table.concat(Rules.modelPool({ models = {} }, general, {}), ',')).toBe('a,b')
        expect(table.concat(Rules.modelPool({ models = { 'x' } }, general, { x = true }), ',')).toBe('a,b')
        expect(table.concat(Rules.modelPool(nil, general, { a = true }), ',')).toBe('b')
    end)
    it('reads looks of one ped (name:head:textures)', function()
        local n, h, t = Rules.modelEntry('my_zombie:5:3')
        expect(n).toBe('my_zombie'); expect(h).toBe(5); expect(t).toBe(3)
        n, h, t = Rules.modelEntry('zombie')
        expect(n).toBe('zombie'); expect(h).toBe(nil); expect(t).toBe(1)
        expect(table.concat(Rules.modelPool({ models = { 'p:1:2', 'q' } }, {}, { p = true }), ',')).toBe('q')
    end)
end)

describe('wandering hordes', function()
    it('says which way a horde is', function()
        local me = { x = 0, y = 0 }
        expect(Rules.compass(me, { x = 0, y = 100 })).toBe('north')
        expect(Rules.compass(me, { x = 100, y = 100 })).toBe('north-east')
        expect(Rules.compass(me, { x = 100, y = 0 })).toBe('east')
        expect(Rules.compass(me, { x = 0, y = -100 })).toBe('south')
        expect(Rules.compass(me, { x = -100, y = 5 })).toBe('west')
    end)
    it('moves toward a point without passing it', function()
        local p = Rules.moveToward({ x = 0, y = 0 }, { x = 10, y = 0 }, 4)
        expect(p.x).toBe(4); expect(p.y).toBe(0)
        p = Rules.moveToward({ x = 0, y = 0 }, { x = 3, y = 0 }, 4)
        expect(p.x).toBe(3)
    end)
    it('ships with hordes on and a warning range', function()
        expect(cfg.hordes.enabled).toBe(true)
        expect(cfg.hordes.warnDistance >= 100).toBe(true)
        expect(cfg.hordes.activateDistance > cfg.hordes.warnDistance).toBe(true)
    end)
end)

describe('combat feel (shipped)', function()
    it('notices anyone within 10 m, knocks down sometimes, hits people in vehicles', function()
        expect(cfg.detection.proximity).toBe(10)
        expect(cfg.attack.knockdownChance).toBe(0.15)
        expect(cfg.attack.pullOutChance).toBe(0.2)
        expect(cfg.attack.vehicleEngineDamage).toBe(120)
        expect(cfg.kinds.walker.chaseSpeed > cfg.kinds.walker.speed).toBe(true)
    end)
end)

describe('spawn points', function()
    local me = { x = 0, y = 0, z = 30 }
    local players = { { source = 1, coords = me }, { source = 2, coords = { x = 300, y = 0, z = 30 } } }
    it('must be in the ring around the player and away from everyone', function()
        expect(Rules.validSpawn(pop, { x = 100, y = 0, z = 30 }, me, players)).toBe(true)
        local _, why = Rules.validSpawn(pop, { x = 20, y = 0, z = 30 }, me, players)
        expect(why).toBe('outside the spawn ring')
        _, why = Rules.validSpawn(pop, { x = 500, y = 0, z = 30 }, me, players)
        expect(why).toBe('outside the spawn ring')
        _, why = Rules.validSpawn(pop, { x = 160, y = 0, z = 30 }, me, { { source = 1, coords = me }, { source = 2, coords = { x = 170, y = 0, z = 30 } } })
        expect(why).toBe('too close to a player')
        _, why = Rules.validSpawn(pop, { x = 'a' }, me, players)
        expect(why).toBe('not a point')
    end)
end)

describe('hits, noise and loot', function()
    it('a hit does damage, sometimes infects and starts bleeding', function()
        local w = cfg.kinds.walker
        local clean = Rules.hit(w, { damage = 0, infection = 0.9, infectionAmount = 0, bleeding = 0.9 })
        expect(clean.damage).toBe(7); expect(clean.infection).toBe(0); expect(clean.bleeding).toBe(0)
        local bad = Rules.hit(w, { damage = 0.999, infection = 0.1, infectionAmount = 0.999, bleeding = 0.1 })
        expect(bad.damage).toBe(11); expect(bad.infection).toBe(12); expect(bad.bleeding).toBe(1)
    end)
    it('zombies within the noise radius hear it; dead ones do not', function()
        local zs = { { id = 1, coords = { x = 50, y = 0, z = 0 } }, { id = 2, coords = { x = 200, y = 0, z = 0 } },
            { id = 3, coords = { x = 10, y = 0, z = 0 }, dead = true } }
        local heard = Rules.hearers(zs, { x = 0, y = 0, z = 0 }, 120)
        expect(#heard).toBe(1); expect(heard[1]).toBe(1)
        expect(#Rules.hearers(zs, { x = 0, y = 0, z = 0 }, 0)).toBe(0)
    end)
    it('loot: by chance, one weighted item with a count in range', function()
        expect(Rules.loot(cfg.loot, 0.9, math.random)).toBe(nil)
        local items = Rules.loot(cfg.loot, 0.0, function(a, b) return a end) -- first pick, lowest count
        expect(items[1].name).toBe('cash'); expect(items[1].count).toBe(5)
        local last = Rules.loot(cfg.loot, 0.0, function(a, b) return b end)
        expect(last[1].name).toBe('scrap_metal'); expect(last[1].count).toBe(2)
    end)
end)

describe('sync compare', function()
    it('finds zombies a game is missing and ones only the game shows', function()
        local missing, ghosts = Rules.compareSync({ 1, 2, 3 }, { 1, 3, 9 }, { [1] = true, [2] = true, [3] = true })
        expect(table.concat(missing, ',')).toBe('2')
        expect(table.concat(ghosts, ',')).toBe('9')
        local m2, g2 = Rules.compareSync({}, {}, {})
        expect(#m2 + #g2).toBe(0)
    end)
end)

