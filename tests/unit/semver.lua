local env = loadCoreFiles({ 'shared/util.lua', 'shared/semver.lua' })
local S = env.WL.Semver

describe('semver', function()
    it('parses full versions', function()
        local v = S.parse('1.2.3')
        expect(v.major).toBe(1); expect(v.minor).toBe(2); expect(v.patch).toBe(3)
    end)
    it('rejects partial or malformed versions', function()
        expect(S.parse('1.2')).toBe(nil)
        expect(S.parse('abc')).toBe(nil)
        expect(S.parse('1.2.3.4')).toBe(nil)
        expect(S.parse(5)).toBe(nil)
    end)
    it('accepts pre-release tags and orders them before the release', function()
        expect(S.compare('1.0.0-beta', '1.0.0')).toBe(-1)
        expect(S.compare('1.0.1', '1.0.0')).toBe(1)
        expect(S.compare('2.0.0', '2.0.0')).toBe(0)
    end)
    it('caret ranges', function()
        expect(S.satisfies('1.4.0', '^1.2.0')).toBe(true)
        expect(S.satisfies('2.0.0', '^1.2.0')).toBe(false)
        expect(S.satisfies('1.1.9', '^1.2.0')).toBe(false)
        expect(S.satisfies('0.2.5', '^0.2.1')).toBe(true)
        expect(S.satisfies('0.3.0', '^0.2.1')).toBe(false)
        expect(S.satisfies('1.9.9', '^1')).toBe(true)
    end)
    it('tilde, comparison, exact, wildcard, AND and OR ranges', function()
        expect(S.satisfies('1.2.9', '~1.2.0')).toBe(true)
        expect(S.satisfies('1.3.0', '~1.2.0')).toBe(false)
        expect(S.satisfies('1.5.0', '>=1.0.0 <1.5.0')).toBe(false)
        expect(S.satisfies('1.4.9', '>=1.0.0 <1.5.0')).toBe(true)
        expect(S.satisfies('1.0.0', '1.0.0')).toBe(true)
        expect(S.satisfies('1.0.1', '1.0.0')).toBe(false)
        expect(S.satisfies('9.9.9', '*')).toBe(true)
        expect(S.satisfies('2.1.0', '^1.0.0 || ^2.0.0')).toBe(true)
        expect(S.satisfies('3.0.0', '^1.0.0 || ^2.0.0')).toBe(false)
    end)
    it('validates ranges, including later alternatives', function()
        expect(S.isValidRange('^1.0.0')).toBe(true)
        expect((S.isValidRange('^x.y'))).toBe(false)
        expect((S.isValidRange('* || ^bad'))).toBe(false)
        expect((S.isValidRange(12))).toBe(false)
    end)
end)
