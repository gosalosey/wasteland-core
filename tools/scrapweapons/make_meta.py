# Writes the three weapon data files of one scrap weapon by copying the
# entries of the game weapon it is based on (same handling, animations and
# hit behaviour) under the new weapon and model names.
#   python make_meta.py <game data folder> <base WEAPON_X> <new WEAPON_WL_X> <model> <label key> <out folder> [Setting=value ...]
# Settings after the folder change single values of the copied weapon, e.g.
# ClipSize=1 sets <ClipSize value="1" />.
# The game data folder holds weapons.meta, weaponanimations.meta and
# weaponarchetypes.meta extracted from the game (update.rpf common/data).
import os, re, sys

DATA, BASE, NEW, MODEL, LABEL, OUT = sys.argv[1:7]
OVERRIDES = [a.split('=', 1) for a in sys.argv[7:]]
os.makedirs(OUT, exist_ok=True)
slug = NEW.lower()


def read(name):
    return open(os.path.join(DATA, name), encoding='utf-8', errors='replace').read()


def block(s, start):
    """The whole <Item ...> element that begins at `start` (nested Items counted)."""
    depth = 0
    for m in re.finditer(r'<Item\b[^>]*?(/?)>|</Item>', s[start:]):
        t = m.group(0)
        if t.startswith('</'): depth -= 1
        elif not t.endswith('/>'): depth += 1
        if depth == 0: return s[start:start + m.end()]
    raise SystemExit('unclosed Item at %d' % start)


# ---- weapons.meta: the CWeaponInfo
s = read('weapons.meta')
i = s.index('<Name>%s</Name>' % BASE)
info = block(s, s.rfind('<Item type="CWeaponInfo">', 0, i))
base_model = re.search(r'<Model>([^<]+)</Model>', info).group(1)
info = info.replace('<Name>%s</Name>' % BASE, '<Name>%s</Name>' % NEW, 1)
info = re.sub(r'<Model>[^<]*</Model>', '<Model>%s</Model>' % MODEL, info, count=1)
info = re.sub(r'<Slot>[^<]*</Slot>', '<Slot>SLOT_%s</Slot>' % NEW[len('WEAPON_'):], info, count=1)
info = re.sub(r'<HumanNameHash>[^<]*</HumanNameHash>', '<HumanNameHash>%s</HumanNameHash>' % LABEL, info, count=1)
info = re.sub(r'<PickupHash>[^<]*</PickupHash>', '<PickupHash />', info, count=1)
info = re.sub(r'<AttachPoints>.*?</AttachPoints>', '<AttachPoints />', info, count=1, flags=re.S)   # no game add-ons
for key, value in OVERRIDES:
    info, n = re.subn(r'<%s value="[^"]*"\s*/>' % key, '<%s value="%s" />' % (key, value), info, count=1)
    if n != 1: raise SystemExit('no setting %s in %s' % (key, BASE))
weapons = ('<?xml version="1.0" encoding="UTF-8"?>\n<!-- %s: copied from %s (generated by tools/scrapweapons/make_meta.py) -->\n'
           '<CWeaponInfoBlob>\n  <SlotNavigateOrder />\n  <SlotBestOrder />\n  <TintSpecValues />\n  <FiringPatternAliases />\n'
           '  <UpperBodyFixupExpressionData />\n  <AimingInfos />\n  <Infos>\n    <Item>\n      <Infos>\n        %s\n      </Infos>\n'
           '    </Item>\n  </Infos>\n  <VehicleWeaponInfos />\n  <Name>%s</Name>\n</CWeaponInfoBlob>\n') % (NEW, BASE, info, NEW)

# ---- weaponanimations.meta: the entries of every animation set that has the base weapon
s = read('weaponanimations.meta')
sets = []
# a set is an Item whose first child is <Fallback> or (DLC files) <WeaponAnimations>
for m in re.finditer(r'<Item key="([A-Za-z_]+)">\s*(?:<Fallback(?: />|>([^<]*)</Fallback>)|<WeaponAnimations>)', s):
    end = m.start() + len(block(s, m.start()))
    sets.append((m.group(1), m.group(2) or '', m.start(), end))
anims = []
for key, fallback, a, b in sets:
    mm = s.find('<Item key="%s">' % BASE, a, b)
    if mm < 0: continue
    item = block(s, mm).replace('<Item key="%s">' % BASE, '<Item key="%s">' % NEW, 1)
    fb = '<Fallback>%s</Fallback>' % fallback if fallback else '<Fallback />'
    anims.append('    <Item key="%s">\n      %s\n      <WeaponAnimations>\n        %s\n      </WeaponAnimations>\n    </Item>' % (key, fb, item))
animations = ('<?xml version="1.0" encoding="UTF-8"?>\n<!-- %s: copied from %s -->\n<CWeaponAnimationsSets>\n  <WeaponAnimationsSets>\n%s\n'
              '  </WeaponAnimationsSets>\n</CWeaponAnimationsSets>\n') % (NEW, BASE, '\n'.join(anims))

# ---- weaponarchetypes.meta: the model, its own textures, draw distance of the base
s = read('weaponarchetypes.meta')
m = re.search(r'<Item>\s*<modelName>%s</modelName>.*?</Item>' % re.escape(base_model), s, re.I | re.S)
lod = re.search(r'<lodDist value="([^"]+)"', m.group(0)).group(1) if m else '50'
archetypes = ('<?xml version="1.0" encoding="UTF-8"?>\n<CWeaponModelInfo__InitDataList>\n  <InitDatas>\n    <Item>\n'
              '      <modelName>%s</modelName>\n      <txdName>%s</txdName>\n      <ptfxAssetName>null</ptfxAssetName>\n'
              '      <lodDist value="%s"/>\n    </Item>\n  </InitDatas>\n</CWeaponModelInfo__InitDataList>\n') % (MODEL, MODEL, lod)

for name, text in (('weapons', weapons), ('weaponanimations', animations), ('weaponarchetypes', archetypes)):
    p = os.path.join(OUT, '%s_%s.meta' % (slug, name))
    open(p, 'w', encoding='utf-8', newline='\n').write(text)
    print('WROTE', p, len(text))
print('SETS', [k for k, _f, a, b in sets if s.find('<Item key="%s">' % BASE, a, b) >= 0])
